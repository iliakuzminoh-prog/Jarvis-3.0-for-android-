    private val typoMap = mapOf(
        "вайфаи" to "вайфай", "вайфи" to "вайфай", "впнн" to "впн", "телеграмм" to "телеграм",
        "ютубчик" to "ютуб", "блютус" to "блютуз", "блютузз" to "блютуз", "настройк" to "настройки",
        "батарею" to "батарея", "громчее" to "громче", "музика" to "музыка", "интернэт" to "интернет"
    )

    fun resolve(raw: String): String? {
        val q = normalize(raw)
        if (q.isBlank()) return null
        intents.firstOrNull { it.phrases.any { p -> q == normalize(p) } }?.let { return it.canonical }

        val tokens = q.split(' ').toSet()
        var best: Intent? = null
        var bestScore = 0.0
        for (intent in intents) {
            val phraseHit = intent.phrases.maxOfOrNull { similarity(q, normalize(it)) } ?: 0.0
            val wordHit = intent.words.count { w -> tokens.contains(normalize(w)) }.toDouble() /
                maxOf(1, intent.words.size).toDouble()
            val score = phraseHit * 0.72 + wordHit * 0.28
            if (score > bestScore) { bestScore = score; best = intent }
        }
        return if (bestScore >= 0.70) best?.canonical else null
    }

    fun explain(raw: String): String {
        val result = resolve(raw)
        return if (result == null) "Не уверен, что правильно понял команду. Скажи её другими словами."
        else "Я понял это как: «$result»."
    }

    fun knownIntentCount(): Int = intents.size

    private fun normalize(s: String): String {
        var x = s.lowercase(Locale.ROOT).replace('ё','е')
        typoMap.forEach { (a,b) -> x = Regex("\\b" + Regex.escape(a) + "\\b").replace(x,b) }
        return x.replace(Regex("[^\\p{L}\\p{N} ]"), " ")
            .replace(Regex("\\s+"), " ").trim()
    }

    private fun similarity(a: String, b: String): Double {
        if (a == b) return 1.0
        val d = levenshtein(a,b)
        return 1.0 - d.toDouble() / maxOf(a.length,b.length,1)
    }

    private fun levenshtein(a: String, b: String): Int {
        val prev = IntArray(b.length + 1) { it }
        val cur = IntArray(b.length + 1)
        for (i in 1..a.length) {
            cur[0] = i
            for (j in 1..b.length) {
                val cost = if (a[i-1] == b[j-1]) 0 else 1
                cur[j] = minOf(cur[j-1] + 1, prev[j] + 1, prev[j-1] + cost)
            }
            for (j in prev.indices) prev[j] = cur[j]
        }
        return prev[b.length]
    }
