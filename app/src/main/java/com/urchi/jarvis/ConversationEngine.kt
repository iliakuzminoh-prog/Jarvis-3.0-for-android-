package com.urchi.jarvis

import java.util.Locale

/**
 * Conversation layer for ordinary Russian speech.
 * It is intentionally separate from command routing: statements such as
 * "я иду в школу" are conversation, not failed commands.
 */
object ConversationEngine {
    fun answer(raw: String): String? {
        val q = normalize(raw)
        if (q.isBlank()) return null

        return when {
            q.matches(Regex("""я (иду|пошел|пошла|пойду|собираюсь идти) в школу.*""")) ->
                "Хорошо. Удачи в школе. Если понадобится что-то быстро узнать или решить, просто напиши JARVIS."
            q.matches(Regex("""я (иду|пошел|пошла|пойду) (домой|на улицу|гулять).*""")) ->
                "Понял. Хорошей дороги."
            q.matches(Regex("""я (сейчас )?(делаю|буду делать|собираюсь делать) .+""")) ->
                "Понял. Если хочешь, можешь рассказать подробнее — я подхвачу разговор."
            q.matches(Regex("""мне (нравится|не нравится) .+""")) ->
                "Понял. Можешь рассказать, что именно тебе нравится или не нравится."
            q.matches(Regex("""я (устал|устала|устал(а)?)""")) ->
                "Понял. Если хочешь, можем говорить коротко и по делу."
            q.matches(Regex("""я (готов|готова)""")) ->
                "Хорошо. Я готов."
            q.matches(Regex("""я (закончил|закончила|сделал|сделала) .+""")) ->
                "Принял. Если есть следующий шаг, говори."
            q.matches(Regex("""у меня (есть|нет) .+""")) ->
                "Понял. Можешь уточнить, что именно у тебя есть или чего нет."
            q.startsWith("мне нужно ") ->
                "Понял. Скажи, что именно нужно сделать, и я попробую выполнить это или объясню, что мне не хватает."
            q.startsWith("я хочу ") ->
                "Понял. Расскажи, что именно ты хочешь получить — постараюсь перевести это в действие."
            q.startsWith("я думаю ") ->
                "Понял твою мысль. Можешь продолжить."
            q == "я иду" || q == "я пошел" || q == "я пошла" ->
                "Понял. Куда идёшь?"
            q == "я здесь" ->
                "Понял. Я тоже на связи."
            q == "я вернулся" || q == "я пришел" || q == "я пришла" ->
                "С возвращением. Я на связи."
            q == "до школы" ->
                "Понял. Если нужна помощь по дороге, скажи."
            else -> null
        }
    }

    private fun normalize(value: String): String =
        value.lowercase(Locale.ROOT).replace('ё', 'е')
            .replace(Regex("""[^\p{L}\p{N} ]"""), " ")
            .replace(Regex("""\s+"""), " ")
            .trim()
}
